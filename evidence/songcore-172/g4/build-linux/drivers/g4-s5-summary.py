#!/usr/bin/env python3
"""g4-s5-summary.py — assemble stage.json + summary.json for the G4
linux-x86_64 build lane from the measured receipts.

Usage: g4-s5-summary.py <receipts-dir> <archived-329-receipt> <drivers-dir>

Nothing here computes a number: every value is read back from a receipt that
was produced by an executed command (facts.env, verify-facts.env,
closure-validation.json, invocations.tsv, compare-329/*).
"""
from __future__ import annotations

import hashlib
import json
import os
import sys
from pathlib import Path

EV = Path(sys.argv[1]).resolve()
OLD_RECEIPT = Path(sys.argv[2])
DRIVERS = Path(sys.argv[3]).resolve()


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def read_env(p: Path) -> dict:
    d = {}
    for line in p.read_text().splitlines():
        if "=" in line:
            k, _, v = line.partition("=")
            d[k] = v
    return d


