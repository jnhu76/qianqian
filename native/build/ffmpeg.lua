-- FFmpeg ownership module: the pinned compile-closure import/replay
-- (ffmpeg-import task, qianqian_av target) and the fail-closed target
-- identity gate (docs/architecture/ffmpeg-minimization.md).

-- The linux/macos default session owns build/artifacts directly (historical
-- layout). A mingw/windows session redirects every artifact into a platform
-- subdir: sharing one dir would let a mingw libsongcore.a silently replace
-- the linux archive (and vice versa) across sessions — the same trap the
-- wasm session avoids with artifacts/wasm below.
local artifact_dir = path.join(os.projectdir(), "build", "artifacts")
if is_plat("mingw", "windows") then
    artifact_dir = path.join(artifact_dir, "windows-mingw-x86_64")
end

-- Which frozen compile closure qianqian_av replays. Defaults to the
-- canonical import manifest (build/ffmpeg-xmake/manifest.json); test and
-- DSP closures are generated by the profile importer into
-- build/minimize/<profile>/ and pointed at with this option.
option("av_manifest")
    set_default("build/ffmpeg-xmake/manifest.json")
    set_showmenu(true)
    set_description("FFmpeg compile-closure manifest to replay")

local ffmpeg_manifest = function ()
    return path.join(os.projectdir(), get_config("av_manifest"))
end

-- Fail-closed target identity (docs/architecture/ffmpeg-minimization.md): the replayed
-- manifest must have been derived for THIS session's target. A Linux
-- manifest carries generated config headers and architecture sources that
-- are not portable, so it must never silently satisfy a Windows/WASM
-- session. The expected id comes from native/ffmpeg/targets/*.json — recipes are
-- the machine-readable target intent, Xmake only matches them.
local expected_target_id = function (target, json)
    local wasm = get_config("wasm")
    if wasm == "wasi" then return "wasm-wasi" end
    if wasm == "emscripten" then return "wasm-emscripten" end
    local found = nil
    local targets_dir = path.join(os.projectdir(), "native", "ffmpeg", "targets")
    for _, recipe_file in ipairs(os.files(path.join(targets_dir, "*.json")) or {}) do
        local r = json.loadfile(recipe_file)
        local plats = (r.xmake or {}).plat or {}
        if type(plats) == "string" then plats = {plats} end
        local plat_ok = false
        for _, p in ipairs(plats) do
            if p == target:plat() then plat_ok = true end
        end
        if plat_ok and (r.xmake or {}).arch == target:arch() then
            found = r.id
            break
        end
    end
    return found
end

-- Returns nil when the manifest identity is acceptable for this session,
-- else a fail-closed error message (raise happens in the callback scope).
-- Binds: target id, platform, arch, and the toolchain-family facts
-- (target_os / cross_prefix) the manifest was derived from — so a MinGW
-- manifest can never satisfy an MSVC session (or vice versa), and a
-- manifest derived from an outdated recipe revision is stale.
local manifest_target_problem = function (manifest_path, target, json)
    local m = json.loadfile(manifest_path)
    local mt = m.target or {}
    if not mt.id then
        return format(
            "%s predates target identity (schema < 2). Re-derive it:\n" ..
            "  native session : xmake ffmpeg-import\n" ..
            "  other targets  : python3 tools/ffmpeg_profile_import.py " ..
            "--target <id> --profile native/ffmpeg/profiles/<capability>.json",
            get_config("av_manifest"))
    end
    local expect = expected_target_id(target, json)
    if not expect then
        return format(
            "no target recipe in native/ffmpeg/targets/ matches this session " ..
            "(plat '%s', arch '%s'). Target provenance is fail-closed: a " ..
            "session may only replay a manifest derived for a proven " ..
            "target recipe (e.g. MSVC is not yet derived; MinGW " ..
            "manifests do not satisfy MSVC sessions).",
            target:plat(), target:arch())
    end
    if mt.id ~= expect then
        return format(
            "manifest target mismatch: %s was derived for '%s' but this " ..
            "session builds '%s'. Derive the matching closure and point " ..
            "--av_manifest at it:\n" ..
            "  python3 tools/ffmpeg_profile_import.py --target %s " ..
            "--profile native/ffmpeg/profiles/<capability>.json",
            get_config("av_manifest"), mt.id, expect, expect)
    end
    local recipe_file = path.join(os.projectdir(), "native", "ffmpeg", "targets",
                                  expect .. ".json")
    local recipe = json.loadfile(recipe_file)
    if not recipe then
        return format("target recipe '%s' is missing from native/ffmpeg/targets/",
                      expect)
    end
    if mt.platform ~= recipe.platform or mt.arch ~= recipe.arch then
        return format(
            "manifest target identity mismatch: %s records %s/%s but the " ..
            "'%s' recipe says %s/%s. Re-derive the closure:\n" ..
            "  python3 tools/ffmpeg_profile_import.py --target %s " ..
            "--profile native/ffmpeg/profiles/<capability>.json",
            get_config("av_manifest"), mt.platform or "?", mt.arch or "?",
            expect, recipe.platform, recipe.arch, expect)
    end
    local ff = recipe.ffmpeg or {}
    local rederive = format(
        " Re-derive the closure:\n" ..
        "  python3 tools/ffmpeg_profile_import.py --target %s " ..
        "--profile native/ffmpeg/profiles/<capability>.json", expect)
    if ff.target_os and mt.target_os ~= ff.target_os then
        return format(
            "manifest is stale or from another toolchain family: %s was " ..
            "derived with target_os '%s' but the '%s' recipe binds '%s'.",
            get_config("av_manifest"), mt.target_os or "?", expect,
            ff.target_os) .. rederive
    end
    if ff.cross_prefix and mt.cross_prefix ~= ff.cross_prefix then
        return format(
            "manifest is stale or from another toolchain family: %s was " ..
            "derived with cross_prefix '%s' but the '%s' recipe binds " ..
            "'%s'.",
            get_config("av_manifest"), mt.cross_prefix or "?", expect,
            ff.cross_prefix) .. rederive
    end
    return nil
end

-- Import is intentionally separate from normal builds. It may invoke FFmpeg's
-- configure/Make once as an upstream oracle, then freezes the exact compile
-- closure in build/ffmpeg-xmake/manifest.json. Normal xmake builds never call
-- FFmpeg Makefiles.
task("ffmpeg-import")
    set_menu {
        usage = "xmake ffmpeg-import",
        description = "Resolve the minimal FFmpeg source closure for Xmake replay"
    }
    on_run(function ()
        import("lib.detect.find_tool")
        local python = find_tool("python3") or find_tool("python")
        assert(python, "python3/python is required for ffmpeg-import")
        os.execv(python.program, {path.join(os.projectdir(), "tools", "ffmpeg_import.py")})
    end)

target("qianqian_av")
    set_kind("static")
    set_default(false)
    set_targetdir(artifact_dir)
    on_load(function (target)
        import("core.base.json")
        -- Do not fail project loading here: `xmake ffmpeg-import` must be able
        -- to run before the manifest exists. before_build below owns the gate.
        local manifest_path = ffmpeg_manifest()
        if not os.isfile(manifest_path) then
            return
        end

        local m = json.loadfile(manifest_path)
        local srcroot = path.join(os.projectdir(), m.source_root)
        local buildroot = path.join(os.projectdir(), m.config_root)

        -- Generated config headers must win over the pristine source tree.
        target:add("includedirs", buildroot, srcroot, {public = true})

        -- WASM sessions replay the closure at -Os (shipping shape). The
        -- manifest keeps the oracle's own flags untouched; codegen level is
        -- a build decision.
        local optimize_flags = function (flags)
            local out = {}
            for _, flag in ipairs(flags) do
                if flag:match("^%-O") then
                    flag = "-Os"
                end
                table.insert(out, flag)
            end
            return out
        end
        local wasm_session = (get_config("wasm") ~= nil and get_config("wasm") ~= false)

        for _, unit in ipairs(m.units) do
            local root = unit.origin == "generated" and buildroot or srcroot
            local source = path.join(root, unit.path)
            local flags = {}
            for _, flag in ipairs(unit.flags or {}) do
                flag = flag:gsub("@SRC@", function () return srcroot end)
                flag = flag:gsub("@BUILD@", function () return buildroot end)
                table.insert(flags, flag)
            end
            if wasm_session then
                flags = optimize_flags(flags)
            end
            if #flags > 0 then
                local force = {}
                force[unit.flag_kind or "cflags"] = flags
                target:add("files", source, {force = force})
            else
                target:add("files", source)
            end
        end
    end)
    before_build(function (target)
        if not os.isfile(ffmpeg_manifest()) then
            raise("FFmpeg source closure is missing. Run `xmake ffmpeg-import` first, then rerun xmake.")
        end
        import("core.base.json")
        local problem = manifest_target_problem(ffmpeg_manifest(), target, json)
        if problem then
            raise(problem)
        end
    end)
